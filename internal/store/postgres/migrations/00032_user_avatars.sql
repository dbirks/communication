-- 00032 — ADR-0083: more than one identity provider, and the one kind whose
-- profile photo cannot be hot-linked.
--
-- Three changes, all additive:
--
--   1. user_avatars: an Entra ID photo arrives as BYTES from Microsoft Graph
--      `GET /me/photo/$value`, authorized by the signer's own access token
--      (https://learn.microsoft.com/en-us/graph/api/profilephoto-get?view=graph-rest-1.0,
--      read 2026-11-11). No browser can load that URL, so the picture lives
--      here and is served from this origin at
--      GET /api/v1/users/{id}/avatar — which is what keeps the app CSP at
--      `img-src 'self'` for Entra while tsidp/generic keep their https URL.
--        * content_type is a closed set, and the server sniffs it
--          (http.DetectContentType) rather than trusting what Graph claimed.
--        * octet_length(bytes) <= 262144 is 256 KiB, the ADR's cap. The API
--          refuses a larger photo before it ever reaches this table; the CHECK
--          is the belt for the caller that forgets.
--        * etag is the sha256 of the bytes, computed on write: the photo changes
--          only when someone signs in again, so a content hash is the exact
--          validator for `Cache-Control: private, max-age=3600`.
--        * ON DELETE CASCADE: a person's photo is not a row to keep after the
--          person is gone (and tests delete users directly).
--
--   2. users.avatar_url gains ONE legal non-https shape: the same-origin path of
--      the route above. The 00031 rule ("only an https URL, or empty") is what
--      stopped an unsanitized provider claim from reaching an <img> src; a path
--      under this origin is equally inert, and it is generated by this server,
--      never copied from a claim. Anything else — http, data:, javascript:, a
--      root-relative path that is not this route — still cannot be stored.
--
--   3. oidc_login_states.provider_id records WHICH provider a handshake was
--      started for, so the callback refuses a code that arrived at a different
--      provider than the one that minted the state (ADR-0083 "State"). NULL is
--      the `default` provider synthesized from the single-issuer environment
--      variables, so rows written by an env-only deployment — and the rows this
--      column replaces — keep their meaning. The CHECK admits the same slug the
--      provider ids are validated against.
--
-- Forward-only per ADR-0013: no existing row changes meaning, nothing is
-- rewritten, no event is appended (09's event families do not cover a profile
-- cache, as with 00008 and 00031). The undo pair exists for test resets only.

-- +goose Up
CREATE TABLE user_avatars (
    user_id      uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    content_type text        NOT NULL CONSTRAINT user_avatars_content_type_check
                             CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    bytes        bytea       NOT NULL CONSTRAINT user_avatars_bytes_size_check
                             CHECK (octet_length(bytes) <= 262144),
    etag         text        NOT NULL,
    updated_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE users
    DROP CONSTRAINT users_avatar_url_check;

ALTER TABLE users
    ADD CONSTRAINT users_avatar_url_check
    CHECK (avatar_url = ''
        OR (length(avatar_url) <= 2048
            AND (avatar_url LIKE 'https://%'
                OR avatar_url ~ '^/api/v1/users/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/avatar$')));

ALTER TABLE oidc_login_states
    ADD COLUMN provider_id text
    CONSTRAINT oidc_login_states_provider_id_check
    CHECK (provider_id IS NULL OR provider_id ~ '^[a-z0-9][a-z0-9_-]{0,63}$');

-- +goose Down
ALTER TABLE oidc_login_states
    DROP CONSTRAINT IF EXISTS oidc_login_states_provider_id_check;

ALTER TABLE oidc_login_states
    DROP COLUMN provider_id;

ALTER TABLE users
    DROP CONSTRAINT users_avatar_url_check;

ALTER TABLE users
    ADD CONSTRAINT users_avatar_url_check
    CHECK (avatar_url = ''
        OR (avatar_url LIKE 'https://%' AND length(avatar_url) <= 2048));

DROP TABLE IF EXISTS user_avatars;
