package apm

// Materializing the manifest (ADR-0030 Amendment 1, APM.md findings F1/F2).
//
// F1: nothing in the codebase ever turned agent_profiles.apm_package_ref into
// an apm.yml, so Stage ran `apm install` in a checkout that tracked no manifest
// and every APM-pinned profile failed its turn with
// "[x] No apm.yml found". F2: `apm install --frozen` *requires* an existing
// apm.lock.yaml, so a fresh checkout with a materialized manifest cannot be
// frozen-installed either — the lock has to come from a resolving install.
//
// The consequence implemented in stage.go: when the checkout carries no
// apm.yml of its own, write the minimal manifest for the profile's ref, run a
// resolving (non-frozen) install to produce the lock, and then let the
// *existing* control decide the launch — sha256(apm.lock.yaml) must equal the
// profile's apm_lock_digest. The bare install is not a loosening: per APM.md
// T-tag-2/3/4 the lock records `resolved_commit`, so a moved tag moves the
// digest and the digest gate refuses. Everything this file generates is named
// in the checkout's git exclusion file so none of it reaches a checkpoint.

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ManifestFileName is the manifest apm reads in a checkout (APM.md spike:
// name/version/description + dependencies.apm).
const ManifestFileName = "apm.yml"

// packageRef is a parsed agent_profiles.apm_package_ref in the grammar
// ADR-0030 §3 fixes: <owner>/<repo>[/<subdir>][#<tag|branch|commit>].
// Subdir is the virtual-subdirectory form proven by APM.md T-tag-5 (it selects
// one skill out of a multi-skill repository); the grammar carries no separate
// skill-name list, so the subset is expressed as `path:` in the object form.
type packageRef struct {
	Source   string // owner/repo
	Subdir   string // may be empty
	Revision string // required: ADR-0030 §3 says a bare ref resolves a branch
}

// parsePackageRef splits and validates a profile's package reference. It is
// strict because the string is interpolated into a YAML manifest written into
// a checkout: an unexpected character is refused, not quoted.
func parsePackageRef(s string) (packageRef, error) {
	raw := strings.TrimSpace(s)
	if raw == "" {
		return packageRef{}, errors.New("apm: empty package ref")
	}
	source, revision, ok := strings.Cut(raw, "#")
	if !ok || revision == "" {
		return packageRef{}, fmt.Errorf("apm: package ref %q carries no #<tag|branch|commit>; a ref without a revision is not pinned (ADR-0030 § 3)", raw)
	}
	if strings.Contains(source, "#") || strings.Contains(revision, "#") {
		return packageRef{}, fmt.Errorf("apm: package ref %q has more than one #", raw)
	}
	for _, seg := range []string{source, revision} {
		if err := checkRefChars(seg); err != nil {
			return packageRef{}, fmt.Errorf("apm: package ref %q: %w", raw, err)
		}
	}
	parts := strings.Split(source, "/")
	if len(parts) < 2 || parts[0] == "" || parts[1] == "" {
		return packageRef{}, fmt.Errorf("apm: package ref %q is not <owner>/<repo>[/<subdir>]", raw)
	}
	for _, p := range parts {
		if p == "" || p == "." || p == ".." {
			return packageRef{}, fmt.Errorf("apm: package ref %q has an empty or traversal path segment", raw)
		}
	}
	return packageRef{
		Source:   strings.Join(parts[:2], "/"),
		Subdir:   strings.Join(parts[2:], "/"),
		Revision: revision,
	}, nil
}

// checkRefChars allows only the characters a GitHub coordinate can hold. It is
// what keeps a hostile profile value from closing the YAML scalar it lands in.
func checkRefChars(s string) error {
	if s == "" {
		return errors.New("empty segment")
	}
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case r == '-', r == '_', r == '.', r == '/':
		default:
			return fmt.Errorf("segment %q contains %q, which is not allowed in a package ref", s, string(r))
		}
	}
	return nil
}

// manifestYAML renders the minimal application manifest in the exact shape
// APM.md's spike used: the plain `owner/repo#ref` string, or the documented
// object form {git:, ref:, path:} when the ref selects a subdirectory.
func (r packageRef) manifestYAML() string {
	var b strings.Builder
	b.WriteString("# Generated by the communication worker from agent_profiles.apm_package_ref\n")
	b.WriteString("# (ADR-0030 Amendment 1). This file is not part of the repository: it is named\n")
	b.WriteString("# in .git/info/exclude so it never reaches a checkpoint or a commit.\n")
	b.WriteString("name: communication-profile-context\n")
	b.WriteString("version: 0.0.0\n")
	b.WriteString("description: APM context pinned by a communication agent profile, staged by the worker\n")
	b.WriteString("dependencies:\n")
	b.WriteString("  apm:\n")
	if r.Subdir == "" {
		fmt.Fprintf(&b, "    - %s#%s\n", r.Source, r.Revision)
	} else {
		fmt.Fprintf(&b, "    - git: %s\n", r.Source)
		fmt.Fprintf(&b, "      ref: %s\n", r.Revision)
		fmt.Fprintf(&b, "      path: %s\n", r.Subdir)
	}
	return b.String()
}

// writeManifest materializes the profile's package ref as apm.yml in the
// checkout. It reports created=false and changes nothing when the checkout
// already carries a manifest of its own — that repository owns its context and
// Stage keeps its old frozen-install behaviour there.
func writeManifest(checkout, ref string) (created bool, err error) {
	path := filepath.Join(checkout, ManifestFileName)
	switch _, err := os.Lstat(path); {
	case err == nil:
		return false, nil
	case !errors.Is(err, os.ErrNotExist):
		return false, fmt.Errorf("apm: cannot read %s in %s: %w", ManifestFileName, checkout, err)
	}
	parsed, err := parsePackageRef(ref)
	if err != nil {
		return false, err
	}
	if err := os.WriteFile(path, []byte(parsed.manifestYAML()), 0o644); err != nil {
		return false, fmt.Errorf("apm: materialize %s: %w", path, err)
	}
	return true, nil
}

// materializedExclusions are the paths a materialized install leaves in the
// checkout, in gitignore form (directories keep their trailing slash): the
// manifest and lock plus the generated trees for the one target that was
// installed (APM.md T-tag-1: claude -> .claude/skills/, codex ->
// .agents/skills/ plus an empty .codex/, and apm_modules/ + apm.lock.yaml for
// both).
func materializedExclusions(target string) []string {
	entries := []string{ManifestFileName, LockFileName, "apm_modules/"}
	switch target {
	case TargetClaude:
		entries = append(entries, ".claude/skills/")
	case TargetCodex:
		entries = append(entries, ".agents/skills/", ".codex/")
	}
	return entries
}

// excludeGenerated names paths in the checkout's git project exclusion file
// (.git/info/exclude), never in a tracked .gitignore. It is append-only and
// idempotent: an entry already listed is not repeated.
//
// Staging runs before the agent exists, so this is the point at which the
// worker's own writes must stop being visible to git; the worker's later
// DeclareExclusions pass over StagedContext.GeneratedPaths stays the second
// line of defence (ADR-0017 D6) and the artifact filter the third.
func excludeGenerated(checkout string, entries []string) error {
	if len(entries) == 0 {
		return nil
	}
	file, err := gitExclusionFile(checkout)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return fmt.Errorf("apm: exclusion dir for %s: %w", file, err)
	}
	existing, err := os.ReadFile(file)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("apm: read %s: %w", file, err)
	}
	have := map[string]bool{}
	for _, line := range strings.Split(string(existing), "\n") {
		have[strings.TrimSuffix(strings.TrimSpace(line), "/")] = true
	}
	var add []string
	for _, e := range entries {
		if !have[strings.TrimSuffix(e, "/")] {
			add = append(add, e)
		}
	}
	if len(add) == 0 {
		return nil
	}
	out := string(existing)
	if out != "" && !strings.HasSuffix(out, "\n") {
		out += "\n"
	}
	out += strings.Join(add, "\n") + "\n"
	if err := os.WriteFile(file, []byte(out), 0o644); err != nil {
		return fmt.Errorf("apm: write %s: %w", file, err)
	}
	return nil
}

// gitExclusionFile resolves the exclusion file git actually consults for this
// checkout: <checkout>/.git/info/exclude for an ordinary clone, and the
// *common* gitdir's info/exclude for a linked worktree — which is what the
// worker's checkouts are (worktrees of a shared mirror, the same file
// internal/workspace/git declares into).
func gitExclusionFile(checkout string) (string, error) {
	gitPath := filepath.Join(checkout, ".git")
	if st, err := os.Lstat(gitPath); err == nil && st.IsDir() {
		return filepath.Join(gitPath, "info", "exclude"), nil
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", fmt.Errorf("apm: cannot read %s: %w", gitPath, err)
	}
	data, err := os.ReadFile(gitPath)
	if err != nil {
		return "", fmt.Errorf("apm: %s is neither a git dir nor a gitdir file: %w", gitPath, err)
	}
	line := strings.TrimSpace(string(data))
	dir, ok := strings.CutPrefix(line, "gitdir:")
	if !ok {
		return "", fmt.Errorf("apm: %s is not a gitdir pointer (%q)", gitPath, bounded(line, 60))
	}
	dir = strings.TrimSpace(dir)
	if !filepath.IsAbs(dir) {
		dir = filepath.Join(checkout, dir)
	}
	if cd, err := os.ReadFile(filepath.Join(dir, "commondir")); err == nil {
		common := strings.TrimSpace(string(cd))
		if common != "" {
			if !filepath.IsAbs(common) {
				common = filepath.Join(dir, common)
			}
			dir = common
		}
	}
	return filepath.Join(dir, "info", "exclude"), nil
}
