#!/usr/bin/env bash
# make_fixture_repo.sh — the disposable M4 exit fixture (§ 7.0 "Disposable
# repo"): a bare git repo exposed as file:///srv/m4/fixtures/app.git.
#
#   usage: bash e2e/m4/make_fixture_repo.sh [OUT_DIR]
#          OUT_DIR defaults to <repo>/.harness/m4-fixtures
#
# The exact same-path bind trick as the M3 harness's .harness/remotes/: the
# compose.m4.yml mount is
#
#   .harness/m4-fixtures:/srv/m4/fixtures:ro
#
# so the file:// URL stored in the database resolves to the same directory
# inside every worker — a fixture mounted at any other path would make every
# prepare fail for a reason that is the lab rather than the code.
#
# Contents (deliberately broken):
#   hello.py            add() with NO docstring
#   tests/test_hello.py asserts __doc__ is present AND add(1,2) == 99
#   pytest.ini          testpaths = tests
# The failing assertion is INTENDED: iteration 1 must fail, and the
# implementer's job is exactly one edit (docs/m4-contract.md § 7.0).
#
# Also shipped: OUT_DIR/bin/m4-exit.sh — the deterministic step helper the
# § 7.1 twins call (pipeline.yaml's `m4-exit.sh [plan|implement|test|review|
# items|issue]`). compose.m4.yml mounts OUT_DIR/bin at /opt/m4/bin and the
# worker commands prepend it to PATH, so the schema-legal bare name resolves
# inside the workers. Pure POSIX sh + GNU tools: the worker image ships
# neither python3 nor pytest, and the test step's static check is exactly the
# two fixture assertions — passes after BOTH implement edits, fails before.
#
# Fault-gates only: M4_HOLD_SECONDS (set from the twin's hold_seconds run input,
# default 0) makes plan/implement/test/review sleep before their work so C4's
# lease freeze, C5's kill and C6's restore land on a live attempt. At 0 the
# script is byte-identical to before: no sleep, no extra bytes on stdout.
#
# Disposable: re-running replaces OUT_DIR/app.git wholesale; it removes only
# its own generated paths and writes nothing else. Fixture lives under the
# gitignored .harness/ tree (lab state, never committed).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")" && cd ../.. && pwd)"
OUT="${1:-$REPO_ROOT/.harness/m4-fixtures}"

# Deterministic lab identity only — never touches the user's global git config
# (the m3 probe library's idiom, docs/compatibility/probes/m3/lib.sh).
export GIT_CONFIG_COUNT=2
export GIT_CONFIG_KEY_0=user.name  GIT_CONFIG_VALUE_0=communication-lab
export GIT_CONFIG_KEY_1=user.email GIT_CONFIG_VALUE_1=lab@communication.invalid
export GIT_TERMINAL_PROMPT=0 GIT_ADVICE=0

BARE="$OUT/app.git"
SEED="$OUT/.seed.$$"
BIN="$OUT/bin"

rm -rf "$BARE" "$SEED" "$BIN"
mkdir -p "$OUT" "$SEED/tests" "$BIN"

# hello.py — no docstring on add(), exactly the § 7.0 description.
cat > "$SEED/hello.py" <<'EOF'
def add(a, b):
    return a + b
EOF

# The intended failure: add(1, 2) == 99 can never pass, and the docstring
# assert gives the implementer a second, fixable reason to edit the file.
cat > "$SEED/tests/test_hello.py" <<'EOF'
from hello import add


def test_add_is_documented():
    assert add.__doc__, "add() must carry a docstring"


def test_add_sums():
    # Intentionally failing on iteration 1 (docs/m4-contract.md § 7.0):
    # the implementer's job is to fix hello.py so this reads == 3 semantics.
    assert add(1, 2) == 99
EOF

cat > "$SEED/pytest.ini" <<'EOF'
[pytest]
testpaths = tests
EOF

cat > "$SEED/README.md" <<'EOF'
# m4 exit fixture

Disposable. `pytest` fails on a clean checkout on purpose — the M4 exit run's
iteration 1 must fail (docs/m4-contract.md § 7.0). Regenerated by
`e2e/m4/make_fixture_repo.sh`; mounted read-only into the workers at
`/srv/m4/fixtures`.
EOF

git init -q -b main "$SEED"
git -C "$SEED" add -A
git -C "$SEED" commit -qm "m4 exit fixture: hello.py + intentionally failing pytest"
git clone --bare -q "$SEED" "$BARE"
rm -rf "$SEED"

# A worker prepares from refs/heads/main; make the bare HEAD say so too.
git --git-dir="$BARE" symbolic-ref HEAD refs/heads/main

# ── m4-exit.sh: the deterministic step helper the § 7.1 twins exec ──────────
# Shipped OUTSIDE the repo (mounted at /opt/m4/bin by compose.m4.yml, on the
# workers' PATH) so the bare `executable: m4-exit.sh` resolves inside the
# worker while the fixture repo stays the tiny Python thing § 7.0 describes.
cat > "$BIN/m4-exit.sh" <<'SCRIPT'
#!/bin/sh
# m4-exit.sh — deterministic fixture steps for the M4 exit twins
# (docs/m4-contract.md § 7.1 C1; generated by e2e/m4/make_fixture_repo.sh).
#
# Exit semantics that make the twin a proof and not a coin flip:
#   plan      -> {"plan": ...}: the two-edit contract (§ 7.0's "exactly one
#                edit per iteration": docstring first, assertion second).
#   implement -> applies ONE edit per invocation (docstring, then ==99->==3),
#                so iteration 1's test run is honestly red and the until loop
#                spends exactly two iterations. {"summary","files_changed"}.
#   test      -> pytest IF the image ships one (it does not today); otherwise
#                a static check of exactly the two fixture assertions. ALWAYS
#                exits 0: a red test is the BUSINESS outcome the passWhen
#                reads (outputs.result.successful), the until cap
#                (maxIterations: 4) is what bounds the loop — § 9.3 slots
#                unchanged, writes build/test-result.json for json_from_path.
#   review    -> {"approved":true,"evidence":...,"findings":[]}; iteration 1
#                is still gated red by the test node, so passWhen decides on
#                facts, never on this constant.
#   items     -> {"items":[{number,title}…]} from M4_FANOUT_COUNT (C8 arm;
#                fanout=false in C1 keeps these rows skipped).
#   issue     -> child step; exits 1 for M4_ISSUE_NUMBER=13 (C8d/e arm).
#
# M4_HOLD_SECONDS (default 0; the twin's hold_seconds run input, env on plan/
# implement/test/review): N>0 makes the step announce the hold on STDERR and sleep
# N seconds before doing anything, so C4/C5/C6's fault gates catch a LIVE attempt.
# 0 = the shipped <1s steps, byte-for-byte unchanged stdout.
#
# POSIX sh + GNU sed/grep only — no python3, no pytest in the worker image.
set -eu

usage() { echo "m4-exit.sh: unknown step '${1:-<none>}' (plan|implement|test|review|items|issue)" >&2; exit 2; }
in_app() {  # implement/test run with cwd repos/app; anything else is a lab fault, said loudly
    [ -f hello.py ] && [ -f tests/test_hello.py ] \
        || { echo "m4-exit.sh $1: cwd is not the fixture app checkout ($(pwd))" >&2; exit 3; }
}
has_doc()  { grep -q '"""' hello.py; }
bad_assert() { grep -Eq 'add\(1, ?2\) *== *99' tests/test_hello.py; }

# hold — opt-in pause on the twin's process.exec steps, fed by the run input
# hold_seconds (docs/compatibility/probes/m4/pipeline.yaml) as M4_HOLD_SECONDS.
# The fault-injection gates (C4 lease freeze, C5 worker kill, C6 restore) have to
# catch an attempt that is STILL RUNNING: these steps are printfs that close in
# <1s, so a 45s compose pause or a docker kill always landed on an attempt that
# had already succeeded (live6 C4/C5/C6). Semantics:
#   unset / 0 / not a plain integer -> no sleep, no output: today's behaviour.
#   N > 0 -> one stderr line (stdout stays the single JSON document the
#            json_from_stdout extractor reads) then `sleep N` BEFORE the step
#            touches anything, so a fenced or killed attempt has published no
#            output, written no file and recorded no checkpoint.
# `items`/`issue` (C8's arms) deliberately carry no hold: C8b samples real
# concurrency, and a hold there would measure the pause instead of the fan-out.
hold() {
    n="${M4_HOLD_SECONDS:-0}"
    case "$n" in ''|*[!0-9]*) n=0 ;; esac
    [ "$n" -eq 0 ] && return 0
    echo "m4-exit.sh $1: holding the attempt open for ${n}s (M4_HOLD_SECONDS=$n)" >&2
    sleep "$n"
}

step="${1:-}"
case "$step" in
plan)
    hold plan
    printf '{"plan": "1. Give add() a docstring so test_add_is_documented passes. 2. Correct the add(1, 2) assertion to true sum semantics so test_add_sums passes."}\n'
    ;;
implement)
    in_app implement
    hold implement
    if ! has_doc; then
        sed -i '/def add(a, b):/a\    """Return the sum of a and b."""' hello.py
        printf '{"summary": "added the add() docstring (iteration 1; the add(1,2) assertion stays red until corrected)", "files_changed": ["hello.py"]}\n'
    elif bad_assert; then
        sed -i -E 's/add\(1, ?2\) *== *99/add(1, 2) == 3/' tests/test_hello.py
        printf '{"summary": "corrected the add(1, 2) assertion to true sum semantics; pytest should be green now", "files_changed": ["tests/test_hello.py"]}\n'
    else
        printf '{"summary": "fixture edits already applied; nothing to change", "files_changed": []}\n'
    fi
    ;;
test)
    in_app test
    hold test
    mkdir -p build
    if command -v pytest >/dev/null 2>&1; then RUNNER=pytest
    elif command -v python3 >/dev/null 2>&1 && python3 -m pytest --version >/dev/null 2>&1; then RUNNER="python3 -m pytest"
    else RUNNER=""; fi
    if [ -n "$RUNNER" ]; then
        set +e; PYTHONPATH=. $RUNNER -q >build/pytest-stdout.txt 2>&1; RC=$?; set -e
    else
        RC=0
        has_doc || RC=1
        if bad_assert; then RC=1; fi
    fi
    if [ "$RC" -eq 0 ]; then SUC=true; else SUC=false; fi
    printf '{"exit_code": %d, "result": {"successful": %s, "packages": [{"name": "tests", "successful": %s}]}}\n' \
        "$RC" "$SUC" "$SUC" >build/test-result.json
    exit 0
    ;;
review)
    hold review
    printf '{"approved": true, "evidence": "deterministic review: plan followed (docstring + corrected assertion), test-result.json carries the machine-checked outcome", "findings": []}\n'
    ;;
items)
    n="${M4_FANOUT_COUNT:-0}"
    items=""
    i=1
    while [ "$i" -le "$n" ]; do
        [ -n "$items" ] && items="$items, "
        items="$items{\"number\": $i, \"title\": \"m4-exit item $i\"}"
        i=$((i + 1))
    done
    printf '{"items": [%s]}\n' "$items"
    ;;
issue)
    n="${M4_ISSUE_NUMBER:-0}"
    if [ "$n" = "13" ]; then
        echo "m4-exit.sh issue 13: failing on purpose (C8d/e child arm)" >&2
        exit 1
    fi
    printf '{"summary": "issue %s implemented (deterministic child)" }\n' "$n"
    ;;
*)
    usage "$step"
    ;;
esac
SCRIPT
chmod 0755 "$BIN/m4-exit.sh"

echo "fixture: $BARE"
echo "url (as stored in the database): file:///srv/m4/fixtures/app.git"
echo "refs: $(git --git-dir="$BARE" for-each-ref --format='%(refname) %(objectname:short)')"
echo "step helper: $BIN/m4-exit.sh (mounted at /opt/m4/bin on the workers' PATH by compose.m4.yml)"
